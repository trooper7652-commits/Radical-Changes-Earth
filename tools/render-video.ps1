# Makes the site's muted visuals: the first 20.25 s of NASA SVS 5313, cropped to the analysis window,
# slowed to 0.75x so it lasts the song's 27 s.
# Run from the repo root:  powershell -ExecutionPolicy Bypass -File tools/render-video.ps1
$ErrorActionPreference = 'Stop'
$video = '.cache/svs5313/nightlights_flat_series_and_change_wZooms_13_EIC_2160p30_h265.mp4'
$visuals = 'site/media/nasa-5313-slowed.mp4'
if (-not (Test-Path $video)) {
  powershell -ExecutionPolicy Bypass -File tools/extract-frames.ps1   # downloads the video
}
New-Item -ItemType Directory -Force -Path site/media | Out-Null
$ffmpeg = (uv run --quiet --no-project --with imageio-ffmpeg python -I -c "import imageio_ffmpeg;print(imageio_ffmpeg.get_ffmpeg_exe())").Trim()

& $ffmpeg -hide_banner -loglevel error -y -t 20.25 -i $video `
  -vf 'crop=3840:2160:1920:0,setpts=PTS/0.75,scale=1920:1080' `
  -c:v libx264 -pix_fmt yuv420p -crf 23 -preset medium -an $visuals
if ($LASTEXITCODE -ne 0) { throw "ffmpeg failed making $visuals" }

# ffmpeg prints the file's duration on stderr; cmd merges it so PowerShell 5.1 does not treat it as an error.
$info = cmd /c "`"$ffmpeg`" -hide_banner -i `"$visuals`" 2>&1" | Out-String
if ($info -notmatch 'Duration: (\d+):(\d+):(\d+\.\d+)') { throw "Could not read the duration of $visuals" }
$seconds = [int]$Matches[1] * 3600 + [int]$Matches[2] * 60 + [double]$Matches[3]
if ([math]::Abs($seconds - 27.0) -gt 0.05) { throw "$visuals lasts $seconds s, expected 27.0 +/- 0.05" }
Write-Output "OK $visuals $seconds s"

# The judged video: the visuals, then the last frame fades into a black credit card, with the song
# (WAV from site/render.html, see tests/site.spec.mjs "render-length") padded with silence to the end.
$wav = 'site/media/radical-changes-song.wav'
$final = 'site/media/radical-changes-30s.mp4'
if (-not (Test-Path $wav)) { throw "$wav is missing: run npx playwright test -g render-length" }
$total = 29.4   # 27.0 s visuals + 2.4 s credit card
$font = 'fontfile=''C\:/Windows/Fonts/arial.ttf'':fontcolor=white:fontsize=44:x=(w-text_w)/2'
$filter = "tpad=stop_mode=clone:stop_duration=2.4,fade=t=out:st=27:d=0.8," +
  "drawtext=${font}:y=h/2-60:text='Visuals\: NASA Scientific Visualization Studio, SVS 5313':enable='gte(t,27.8)'," +
  "drawtext=${font}:y=h/2+10:text='Music\: Radical changes':enable='gte(t,27.8)'"
# A filter script file avoids PowerShell 5.1 mangling the quotes inside the filter.
$filterFile = '.cache/credit-filter.txt'
Set-Content -Path $filterFile -Value $filter -Encoding ASCII
& $ffmpeg -hide_banner -loglevel error -y -i $visuals -i $wav `
  -/vf $filterFile -af 'apad' -t $total `
  -c:v libx264 -pix_fmt yuv420p -crf 23 -preset medium -c:a aac -b:a 192k `
  -metadata 'title=Radical changes' `
  -metadata 'comment=Music generated by code written with AI assistance; see SI_DISCLOSURE.md' $final
if ($LASTEXITCODE -ne 0) { throw "ffmpeg failed making $final" }

$info = cmd /c "`"$ffmpeg`" -hide_banner -i `"$final`" 2>&1" | Out-String
if ($info -notmatch 'Duration: (\d+):(\d+):(\d+\.\d+)') { throw "Could not read the duration of $final" }
$seconds = [int]$Matches[1] * 3600 + [int]$Matches[2] * 60 + [double]$Matches[3]
$audioStreams = ([regex]::Matches($info, 'Stream #.*Audio:')).Count
$size = if ($info -match 'Video: h264.*?(\d{3,4}x\d{3,4})') { $Matches[1] } else { 'unknown' }
$comment = $info -match 'comment\s*:\s*Music generated by code written with AI assistance; see SI_DISCLOSURE.md'
Write-Output "duration=$seconds s  resolution=$size  audio streams=$audioStreams  comment tag=$comment"
if ($seconds -gt 29.5 -or $size -ne '1920x1080' -or $audioStreams -ne 1 -or -not $comment) { throw "$final failed its checks" }
Write-Output "OK $final"
